// Isolated synthetic API: no live recordings or retention settings are changed.
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { createServer } from "vite";
process.chdir(fileURLToPath(new URL("..", import.meta.url)));
const server = await createServer({ server: { host: "127.0.0.1", port: 0 } });
let browser;
try {
  await server.listen();
  const origin = server.resolvedUrls.local[0];
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  const ids = ["recordings", "current", "failed_capture", "failed_build", "superseded", "failed_publish", "logs", "other"];
  const categories = ids.map((id,i) => {
    const days = id === "other" ? [] : Array.from({length: 45}, (_,d) => ({ date: new Date(Date.UTC(2026,7,16+d)).toISOString().slice(0,10), bytes: Math.round((Math.sin(d*.8)**2+.1)*(8-i)*4000000), files: 3 }));
    const undated_bytes = id === "other" ? 8000000 : 1000;
    return { id, bytes: days.reduce((sum,d) => sum+d.bytes,0)+undated_bytes, files: days.length*3+1, undated_bytes, undated_files: 1, days };
  });
  const fixture = { measured_at: "2026-09-29T10:00:00Z", published: [{id:"published",label:"Published recordings",bytes:983000000}], directories: [{id:"current",bytes:1}], categories };
  let fail = false, empty = false, posts = 0, puts = 0;
  const forever = {forever:true};
  const settings = {version:3,revision:0,schedule:{time:"02:00",timezone:"UTC"},recordings:forever,current:forever,logs:forever,history:{mode:"group",policy:forever,fine:Object.fromEntries(ids.slice(2,6).map(id => [id,forever]))}};
  await page.route("**/storage-charts-fixture", route => route.fulfill({contentType:"text/html",body:`<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="app" style="max-width:980px;margin:auto;padding:20px"></div><script type="module">
    import { mount } from '/node_modules/.vite/deps/svelte.js';
    import Settings from '/src/Settings.svelte';
    import '/src/app.css';
    window.__CASSINI_CONFIG__ = {operatorBasePath:'/operator'};
    mount(Settings,{target:document.getElementById('app'),props:{panel:'storage'}});
  </script></body></html>`}));
  await page.route(`${origin}operator/**`, route => {
    const request = route.request();
    if (request.method() === "PUT") puts++;
    if (new URL(request.url()).pathname === "/operator/storage/retention") return route.fulfill({json:settings});
    if (request.method() === "POST") posts++;
    if (fail) return route.fulfill({status:503,json:{error:"Synthetic scan failure"}});
    return route.fulfill({json: empty ? {...fixture,categories:categories.map(c=>({...c,bytes:0,files:0,undated_bytes:0,undated_files:0,days:[]}))} : fixture});
  });
  await page.goto(new URL("storage-charts-fixture",origin).href);
  await page.getByRole("button",{name:"Recalculate",exact:true}).waitFor();
  await page.waitForFunction(()=>!document.querySelector('button.recalculate')?.disabled);
  assert.equal(posts,1);
  await page.getByRole("heading",{name:"Retention policies",exact:true}).waitFor();
  await page.getByRole("button",{name:/Explore Source recordings:/}).click();
  const source = page.locator("#category-recordings");
  await source.getByLabel("Source recordings precision",{exact:true}).selectOption("7");
  assert.equal(await source.locator(".bar-target").count(),7);
  await source.locator(".bar-target").first().focus();
  assert.match(await source.locator(".bar-detail").innerText(),/2026/);
  await source.getByText("View chart data",{exact:true}).click();
  assert.equal(await source.locator("tbody tr").count(),7);
  await source.getByLabel("Source recordings time range",{exact:true}).selectOption("custom");
  await source.getByLabel("Source recordings from date").fill("2026-09-01");
  await source.getByLabel("Source recordings through date").fill("2026-09-07");
  assert.equal(await source.locator(".bar-target").count(),1);
  await source.getByLabel("Source recordings through date").fill("2026-08-31");
  await source.getByRole("alert").filter({hasText:"end date"}).waitFor();
  await source.getByLabel("Source recordings through date").fill("2026-09-07");
  await source.getByLabel("Source recordings precision",{exact:true}).selectOption("custom");
  await source.getByLabel("Source recordings days per bar").fill("0");
  await source.getByRole("alert").filter({hasText:"whole number"}).waitFor();
  await source.getByLabel("Source recordings days per bar").fill("3");
  assert.equal(await source.locator(".bar-target").count(),3);
  await page.getByRole("button",{name:/Explore Logs:/}).click();
  assert.equal(await page.getByLabel("Logs time range",{exact:true}).inputValue(),"all");
  assert.equal(await source.getByLabel("Source recordings time range",{exact:true}).inputValue(),"custom");
  await page.getByLabel("Split attempt history").check();
  await page.getByRole("button",{name:/Explore Failed recordings:/}).waitFor();
  assert.equal(await page.locator(".comparison-row").count(),8);
  await page.getByRole("button",{name:/Explore Other local files:/}).click();
  await page.locator("#category-other").getByText("No dated files to plot in this category.").waitFor();
  assert.equal(puts,0,"chart controls must not save policies");
  assert.equal(posts,1,"chart controls must not rescan files");
  await page.getByLabel("Split attempt history").uncheck();
  await source.getByLabel("Source recordings time range",{exact:true}).selectOption("all");
  await source.getByLabel("Source recordings precision",{exact:true}).selectOption("1");
  await source.getByText("View chart data",{exact:true}).click();
  const output = fileURLToPath(new URL("../../scratch/storage-charts/",import.meta.url));
  await mkdir(output,{recursive:true});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:output+"desktop.png",fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:output+"mobile.png",fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth), "mobile must not overflow: " + JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('*')].filter(el => el.getBoundingClientRect().right > innerWidth).slice(0,12).map(el => ({tag:el.tagName,cls:el.className,width:el.getBoundingClientRect().width})))));
  await page.emulateMedia({colorScheme:"dark"});
  await page.screenshot({path:output+"dark-mobile.png",fullPage:true});
  fail = true;
  await page.getByRole("button",{name:"Recalculate",exact:true}).click();
  await page.getByText(/Couldn’t recalculate:/).waitFor();
  assert.equal(await page.locator(".comparison-row").count(),5,"refresh error keeps last report");
  fail = false; empty = true;
  await page.getByRole("button",{name:"Recalculate",exact:true}).click();
  await source.getByText("No retained files in this category.").waitFor();
  assert.deepEqual(errors,[]);
  console.log("Storage charts browser checks passed: independent controls, UTC ranges, custom precision, history split, unknown/empty data, refresh failure, mobile layout, no policy writes.");
} finally { await browser?.close(); await server.close(); }
