#!/usr/bin/env python3
from __future__ import annotations

import argparse
import array
import json
import subprocess
import sys
from pathlib import Path

from sync_signal_verify import detect_audio_event, detect_video_pulse


def run_command(cmd: list[str]) -> bytes:
    result = subprocess.run(cmd, capture_output=True, check=False)
    if result.returncode != 0:
        stderr = result.stderr.decode("utf-8", errors="replace").strip()
        raise RuntimeError(f"command failed ({' '.join(cmd)}): {stderr}")
    return result.stdout


def probe_streams(input_path: Path) -> list[dict]:
    data = run_command(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_streams",
            "-of",
            "json",
            str(input_path),
        ]
    )
    parsed = json.loads(data.decode("utf-8"))
    streams = parsed.get("streams") or []

    audio_ord = 0
    video_ord = 0
    for stream in streams:
        ctype = str(stream.get("codec_type") or "")
        if ctype == "audio":
            stream["_ord"] = audio_ord
            audio_ord += 1
        elif ctype == "video":
            stream["_ord"] = video_ord
            video_ord += 1
    return streams


def extract_audio_samples(input_path: Path, audio_ord: int, sample_rate: int) -> list[float]:
    payload = run_command(
        [
            "ffmpeg",
            "-v",
            "error",
            "-i",
            str(input_path),
            "-map",
            f"0:a:{audio_ord}",
            "-ac",
            "1",
            "-ar",
            str(sample_rate),
            "-f",
            "s16le",
            "-",
        ]
    )
    values = array.array("h")
    values.frombytes(payload)
    if sys.byteorder != "little":
        values.byteswap()
    return [sample / 32768.0 for sample in values]


def extract_video_luma(input_path: Path, video_ord: int, fps: float, width: int = 64, height: int = 36) -> list[float]:
    payload = run_command(
        [
            "ffmpeg",
            "-v",
            "error",
            "-i",
            str(input_path),
            "-map",
            f"0:v:{video_ord}",
            "-vf",
            f"fps={fps},scale={width}:{height},format=gray",
            "-f",
            "rawvideo",
            "-",
        ]
    )
    frame_size = width * height
    if frame_size <= 0:
        return []

    frame_count = len(payload) // frame_size
    if frame_count == 0:
        return []

    mv = memoryview(payload)
    means: list[float] = []
    for idx in range(frame_count):
        start = idx * frame_size
        frame = mv[start : start + frame_size]
        means.append(sum(frame) / float(frame_size))
    return means


def stream_text(stream: dict) -> str:
    tags = stream.get("tags") or {}
    values = [str(value).strip().lower() for value in tags.values() if str(value).strip()]
    values.append(str(stream.get("codec_name") or "").lower())
    return " ".join(values)


def stream_matches_participant(stream: dict, participant: dict) -> bool:
    haystack = stream_text(stream)
    pid = str(participant.get("id") or "").strip().lower()
    name = str(participant.get("name") or "").strip().lower()
    return (pid and pid in haystack) or (name and name in haystack)


def pick_participant_stream(streams: list[dict], participant: dict, codec_type: str, fallback_ord: int | None = None) -> int | None:
    selected = [stream for stream in streams if str(stream.get("codec_type")) == codec_type]
    matches = [stream for stream in selected if stream_matches_participant(stream, participant)]
    if len(matches) == 1:
        return int(matches[0].get("_ord"))
    if len(matches) > 1 and fallback_ord is not None:
        for stream in matches:
            if int(stream.get("_ord")) == fallback_ord:
                return int(stream.get("_ord"))
        return int(matches[0].get("_ord"))
    if len(matches) > 1:
        return int(matches[0].get("_ord"))
    if fallback_ord is not None and 0 <= fallback_ord < len(selected):
        return fallback_ord
    return None


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Verify deterministic sync markers in multitrack or composed recordings.")
    parser.add_argument("--input", required=True, help="Input recording path (MKV/MP4).")
    parser.add_argument("--manifest", required=True, help="Path to signals.json generated by prepare-sync-signals.sh.")
    parser.add_argument("--mode", choices=["auto", "multitrack", "composed"], default="auto")
    parser.add_argument("--sample-rate", type=int, default=16000)
    parser.add_argument("--video-fps", type=float, default=20.0)
    parser.add_argument("--max-av-skew", type=float, default=0.35)
    parser.add_argument("--min-hit-ratio", type=float, default=0.70)
    parser.add_argument("--min-audio-ratio", type=float, default=1.80)
    parser.add_argument("--min-audio-rms", type=float, default=0.008)
    parser.add_argument("--min-video-delta", type=float, default=12.0)
    parser.add_argument("--verbose", action="store_true")
    return parser.parse_args()


def verify_participant(
    participant: dict,
    event_times: list[float],
    audio_samples: list[float],
    all_frequencies: list[float],
    luma_values: list[float],
    sample_rate: int,
    video_fps: float,
    max_av_skew: float,
    min_audio_ratio: float,
    min_audio_rms: float,
    min_video_delta: float,
    verbose: bool,
) -> tuple[int, int]:
    participant_name = str(participant.get("name") or participant.get("id") or "unknown")
    freq = float(participant.get("frequency_hz"))

    hits = 0
    total = len(event_times)
    for expected in event_times:
        audio = detect_audio_event(
            samples=audio_samples,
            sample_rate=sample_rate,
            expected_sec=expected,
            target_hz=freq,
            all_frequencies_hz=all_frequencies,
            min_ratio=min_audio_ratio,
            min_rms=min_audio_rms,
        )
        video = detect_video_pulse(
            luma_values=luma_values,
            fps=video_fps,
            expected_sec=expected,
            min_luma_delta=min_video_delta,
        )
        skew = abs(audio.detected_sec - video.detected_sec)
        ok = audio.ok and video.ok and skew <= max_av_skew

        if verbose:
            print(
                f"[verify] participant={participant_name} expected={expected:.3f}s "
                f"audio={audio.detected_sec:.3f}s ratio={audio.ratio:.2f} rms={audio.rms:.4f} "
                f"video={video.detected_sec:.3f}s luma={video.peak_luma:.2f} skew={skew:.3f}s ok={ok}"
            )
        if ok:
            hits += 1

    print(f"[verify] participant={participant_name} hits={hits}/{total}")
    return hits, total


def verify_multitrack(args: argparse.Namespace, streams: list[dict], manifest: dict) -> int:
    participants = manifest.get("participants") or []
    if not participants:
        raise RuntimeError("manifest has no participants")

    all_frequencies = [float(p["frequency_hz"]) for p in participants]
    failed = 0

    for index, participant in enumerate(participants):
        audio_ord = pick_participant_stream(streams, participant, "audio", fallback_ord=index)
        video_ord = pick_participant_stream(streams, participant, "video", fallback_ord=index)
        if audio_ord is None or video_ord is None:
            print(f"[verify] missing mapped streams for participant={participant.get('name')}", file=sys.stderr)
            failed += 1
            continue

        audio_samples = extract_audio_samples(Path(args.input), audio_ord, args.sample_rate)
        luma_values = extract_video_luma(Path(args.input), video_ord, args.video_fps)
        events = [float(x) for x in participant.get("event_times_sec") or []]
        if not events:
            print(f"[verify] no events in manifest for participant={participant.get('name')}", file=sys.stderr)
            failed += 1
            continue

        hits, total = verify_participant(
            participant=participant,
            event_times=events,
            audio_samples=audio_samples,
            all_frequencies=all_frequencies,
            luma_values=luma_values,
            sample_rate=args.sample_rate,
            video_fps=args.video_fps,
            max_av_skew=args.max_av_skew,
            min_audio_ratio=args.min_audio_ratio,
            min_audio_rms=args.min_audio_rms,
            min_video_delta=args.min_video_delta,
            verbose=args.verbose,
        )
        ratio = (hits / total) if total else 0.0
        if ratio < args.min_hit_ratio:
            failed += 1
            print(
                f"[verify] participant {participant.get('name')} failed hit ratio: {ratio:.2f} < {args.min_hit_ratio:.2f}",
                file=sys.stderr,
            )

    if failed:
        return 1
    print("[verify] multitrack sync verification passed")
    return 0


def verify_composed(args: argparse.Namespace, streams: list[dict], manifest: dict) -> int:
    participants = manifest.get("participants") or []
    if not participants:
        raise RuntimeError("manifest has no participants")

    audio_streams = [stream for stream in streams if str(stream.get("codec_type")) == "audio"]
    video_streams = [stream for stream in streams if str(stream.get("codec_type")) == "video"]
    if not audio_streams or not video_streams:
        raise RuntimeError("composed file must contain at least one audio and one video stream")

    audio_ord = int(audio_streams[0].get("_ord"))
    video_ord = int(video_streams[0].get("_ord"))
    audio_samples = extract_audio_samples(Path(args.input), audio_ord, args.sample_rate)
    luma_values = extract_video_luma(Path(args.input), video_ord, args.video_fps)

    all_frequencies = [float(p["frequency_hz"]) for p in participants]

    total_hits = 0
    total_events = 0
    for participant in participants:
        events = [float(x) for x in participant.get("event_times_sec") or []]
        if not events:
            continue
        hits, total = verify_participant(
            participant=participant,
            event_times=events,
            audio_samples=audio_samples,
            all_frequencies=all_frequencies,
            luma_values=luma_values,
            sample_rate=args.sample_rate,
            video_fps=args.video_fps,
            max_av_skew=args.max_av_skew,
            min_audio_ratio=args.min_audio_ratio,
            min_audio_rms=args.min_audio_rms,
            min_video_delta=args.min_video_delta,
            verbose=args.verbose,
        )
        total_hits += hits
        total_events += total

    ratio = (total_hits / total_events) if total_events else 0.0
    print(f"[verify] composed hit ratio={ratio:.2f} ({total_hits}/{total_events})")
    if ratio < args.min_hit_ratio:
        print(
            f"[verify] composed sync verification failed: ratio {ratio:.2f} < {args.min_hit_ratio:.2f}",
            file=sys.stderr,
        )
        return 1

    print("[verify] composed sync verification passed")
    return 0


def main() -> int:
    args = parse_args()
    input_path = Path(args.input)
    manifest_path = Path(args.manifest)

    if not input_path.is_file():
        print(f"input not found: {input_path}", file=sys.stderr)
        return 2
    if not manifest_path.is_file():
        print(f"manifest not found: {manifest_path}", file=sys.stderr)
        return 2

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    streams = probe_streams(input_path)

    mode = args.mode
    if mode == "auto":
        audio_count = len([stream for stream in streams if str(stream.get("codec_type")) == "audio"])
        mode = "multitrack" if audio_count > 1 else "composed"

    if mode == "multitrack":
        return verify_multitrack(args, streams, manifest)
    return verify_composed(args, streams, manifest)


if __name__ == "__main__":
    raise SystemExit(main())
